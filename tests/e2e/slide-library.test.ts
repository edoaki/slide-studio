import assert from 'node:assert/strict';
import { mkdtemp, writeFile, readFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createRequire } from 'node:module';
import test from 'node:test';
import { _electron } from 'playwright-core';
import { Workspace } from '../../packages/core/src/workspace.js';
const require=createRequire(import.meta.url);
test('search, preview thumbnail, import across topics and undo in Electron', {timeout:90000},async t=>{
 const temp=await mkdtemp(join(tmpdir(),'studio-slide-library-'));
 const ws=Workspace.open(join(temp,'workspace'));ws.new_deck('past','old');ws.new_deck('now','new');
 await writeFile(ws.qmd('past'),'---\ntitle: Past\ntopic: old\n---\n\n## 検索したい図\n\n結果は良好 [@known]\n');
 await writeFile(ws.bib('past'),'@article{known,title={Known result},author={Doe, Jane},year={2025}}');
 const before=await readFile(ws.qmd('now'),'utf8');
 const env:Record<string,string>=Object.fromEntries(Object.entries(process.env).filter((e):e is [string,string]=>e[1]!==undefined));env.SLIDE_STUDIO_ELECTRON_HOME=join(temp,'profile');delete env.ELECTRON_RUN_AS_NODE;
 const installed=process.env.SLIDE_STUDIO_TEST_APP;
 const app=await _electron.launch({executablePath:installed?.endsWith('.app')?join(installed,'Contents/MacOS/Slide Studio'):installed||require('electron'),args:[...(installed?[]:[join(process.cwd(),'dist/apps/desktop/main.js')]),'--root',ws.root],env});
 t.after(async()=>{await app.close();await rm(temp,{recursive:true,force:true});});
 const page=await app.firstWindow();const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await page.waitForFunction(()=>!!sessionStorage.getItem('slide-studio:admin-token'));
 await page.goto(new URL('/deck/now',page.url()).href);
 await page.getByRole('button',{name:'スライドを探す',exact:true}).click();
 const dialog=page.getByRole('dialog',{name:'スライドを探す'});
 await dialog.getByRole('searchbox').fill('known');await dialog.getByRole('button',{name:'検索',exact:true}).click();
 await dialog.locator('.sl-deck-card').click();
 await dialog.getByRole('checkbox').waitFor();assert.equal(await dialog.getByRole('checkbox').count(),1);
 await dialog.locator('.slide-library-thumb img').waitFor({timeout:45000});
 await dialog.getByRole('checkbox').check();
 assert.match(await dialog.locator('.sl-summary').innerText(),/1 ページを選択中/);
 await page.screenshot({path:join(tmpdir(),'slide-library-preview.png')});
 await dialog.getByRole('button',{name:'選択を解除'}).click();
 assert.equal(await dialog.getByRole('checkbox').isChecked(),false);
 await page.evaluate(()=>document.documentElement.dataset.theme='dark');
 await page.screenshot({path:join(tmpdir(),'slide-library-dark.png')});
 await page.evaluate(()=>document.documentElement.dataset.theme='light');
 await dialog.getByRole('checkbox').check();await dialog.getByRole('button',{name:'指定位置に挿入',exact:true}).click();
 await page.locator('.overview-insert').last().click();
 await dialog.waitFor({state:'detached'});
 assert.match(await readFile(ws.qmd('now'),'utf8'),/検索したい図/);assert.match(await readFile(ws.bib('now'),'utf8'),/@article\{known/);
 await page.keyboard.press('Meta+z');
 await page.waitForTimeout(500);
 assert.equal(await readFile(ws.qmd('now'),'utf8'),before);assert.deepEqual(errors,[]);
});
