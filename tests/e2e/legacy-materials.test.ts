import assert from 'node:assert/strict';
import { mkdtemp, readFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createRequire } from 'node:module';
import test from 'node:test';
import { _electron } from 'playwright-core';
import { Workspace } from '../../packages/core/src/legacy-workspace.js';
const require=createRequire(import.meta.url);
test('original materials panel uploads, previews, renames, deletes and undoes in Electron', {timeout:60000}, async t=>{
  const temp=await mkdtemp(join(tmpdir(),'studio-materials-e2e-'));

  const ws=Workspace.open(join(temp,'workspace'));ws.new_deck('talk','test');
  const env:Record<string,string>=Object.fromEntries(Object.entries(process.env).filter((entry): entry is [string,string]=>entry[1]!==undefined));env.SLIDE_STUDIO_ELECTRON_HOME=join(temp,'profile');delete env.ELECTRON_RUN_AS_NODE;
  const app=await _electron.launch({executablePath:require('electron'),args:[join(process.cwd(),'dist/apps/desktop/main.js'),'--root',ws.root],env});
  t.after(async()=>{await app.close();await rm(temp,{recursive:true,force:true});});
  const page=await app.firstWindow();const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message));
  await page.waitForFunction(()=>!!sessionStorage.getItem('slide-studio:admin-token'));
  await page.goto(new URL('/deck/talk',page.url()).href);
  await page.getByRole('tab',{name:'参考資料',exact:true}).click();
  await page.getByRole('button',{name:'新しいフォルダ',exact:true}).click();
  await page.getByRole('textbox',{name:'名前',exact:true}).fill('結果');
  await page.getByRole('textbox',{name:'名前',exact:true}).press('Enter');
  await page.locator('.mt-row[data-path="結果"]').waitFor();
  await page.locator('.mt-row[data-path="結果"]').click();
  const chooser=page.waitForEvent('filechooser');
  await page.getByRole('button',{name:'パソコンからファイルを追加',exact:true}).click();
  await (await chooser).setFiles({name:'data.csv',mimeType:'text/csv',buffer:Buffer.from('x,y\n1,2\n')});
  const row=page.locator('.mt-row[data-path="結果/data.csv"]');await row.waitFor();await row.click();
  await page.locator('.mt-pvb pre').waitFor();
  assert.equal(await page.locator('.mt-pvb pre').textContent(),'x,y\n1,2\n');
  assert.equal(await readFile(join(ws.deck_dir('talk'),'materials/結果/data.csv'),'utf8'),'x,y\n1,2\n');
  await row.press('F2');await page.getByRole('textbox',{name:'名前',exact:true}).fill('renamed.csv');await page.getByRole('textbox',{name:'名前',exact:true}).press('Enter');
  const renamed=page.locator('.mt-row[data-path="結果/renamed.csv"]');await renamed.waitFor();await renamed.press('Delete');
  await page.getByRole('dialog',{name:'参考資料を削除'}).getByRole('button',{name:'削除',exact:true}).click();
  await renamed.waitFor({state:'detached'});
  await page.keyboard.press('Meta+z');await renamed.waitFor();
  assert.equal(await readFile(join(ws.deck_dir('talk'),'materials/結果/renamed.csv'),'utf8'),'x,y\n1,2\n');
  assert.deepEqual(errors,[]);
});
