import assert from 'node:assert/strict';
import test from 'node:test';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createRequire } from 'node:module';
import { _electron } from 'playwright-core';
const require = createRequire(import.meta.url);
test('settings isolate editing, persist across restart and control native zoom', {timeout:120000}, async t => {
  const temp = await mkdtemp(join(tmpdir(),'studio-settings-ui-'));
  const env: Record<string,string> = Object.fromEntries(Object.entries(process.env).filter((e):e is [string,string]=>e[1]!==undefined));
  env.SLIDE_STUDIO_ELECTRON_HOME=join(temp,'profile'); delete env.ELECTRON_RUN_AS_NODE;
  const launch = () => _electron.launch({ executablePath:require('electron'), args:[join(process.cwd(),'dist/apps/desktop/main.js')], env });
  let app = await launch();
  t.after(async()=>{await app.close();await rm(temp,{recursive:true,force:true});});
  let page = await app.firstWindow();
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
  await page.route('**/api/env', route => route.fulfill({json:{items:[{name:'Pandoc',ok:true,detail:'/Applications/Slide Studio.app/Contents/Resources/'+ 'long-folder/'.repeat(15) + 'pandoc',fix:'This warning must stay hidden'},{name:'Chromium',ok:false,detail:'Unavailable',fix:'Repair required'}]}}));
  await page.getByRole('button',{name:'設定',exact:true}).click();
  let dialog=page.getByRole('dialog',{name:'設定',exact:true});
  assert.equal(await dialog.locator('[data-tab]').count(),4);
  assert.equal(await page.evaluate(async()=>(await fetch('/api/settings')).status),401);
  assert.equal(await page.evaluate(async()=>(await fetch('/api/settings',{method:'POST',headers:{'Content-Type':'application/json','X-Studio-Token':sessionStorage.getItem('slide-studio:admin-token')!},body:JSON.stringify({zoom:0})})).status),400);
  await dialog.locator('[data-tab=appearance]').click();
  await dialog.getByLabel('カラーテーマ',{exact:true}).selectOption('dark');
  await page.waitForFunction(()=>document.documentElement.dataset.theme==='dark');
  await dialog.getByLabel('画面下にキー操作の案内を表示',{exact:true}).uncheck();
  await page.waitForFunction(()=>document.documentElement.dataset.keyHints==='false');
  await dialog.getByLabel('アプリの表示倍率',{exact:true}).selectOption('125');
  await page.waitForFunction(()=>document.querySelector<HTMLSelectElement>('[data-setting=zoom]')?.value==='125');
  await page.waitForTimeout(200);
  const window = await app.browserWindow(page);
  assert.equal(await window.evaluate(w=>w.webContents.getZoomFactor()),1.25);
  await page.keyboard.press('Meta+0');
  await page.waitForFunction(()=>document.querySelector<HTMLSelectElement>('[data-setting=zoom]')?.value==='100');
  await dialog.locator('[data-tab=general]').click();
  await dialog.locator('.settings-environment summary').click();
  await dialog.locator('[data-section=general] .settings-diagnostics li').first().waitFor();
  assert.equal(await dialog.locator('.diagnostic-fix').count(),1);
  assert.equal(await dialog.locator('.diagnostic-fix').textContent(),'Repair required');
  const pandoc = dialog.locator('.diagnostic-head b').first();
  const labelBox = await pandoc.boundingBox(); assert.ok(labelBox && labelBox.width > 40 && labelBox.height < 30);
  assert.ok(await dialog.locator('.settings-content').evaluate(e=>e.scrollWidth<=e.clientWidth));
  await dialog.locator('.settings-content').evaluate(e=>{e.scrollTop=e.scrollHeight;});
  await page.screenshot({path:'/tmp/slide-studio-settings-general.png'});
  await dialog.locator('[data-tab=shortcuts]').click();
  await dialog.getByText('現在のスライドから発表',{exact:true}).waitFor();
  await dialog.locator('[data-tab=appearance]').click();
  await page.screenshot({path:'/tmp/slide-studio-settings.png'});
  await page.keyboard.press('Escape'); await dialog.waitFor({state:'hidden'});
  await page.getByRole('button',{name:'設定',exact:true}).click();
  await dialog.locator('[data-close]').click(); await dialog.waitFor({state:'hidden'});
  await page.getByRole('button',{name:'設定',exact:true}).click();
  await dialog.locator('.settings-main > header h2').click(); assert.ok(await dialog.isVisible());
  await page.mouse.click(2,2); await dialog.waitFor({state:'hidden'});
  await page.locator('.cards .card').first().click();
  await page.locator('#pageCount').filter({hasText:/\d/}).waitFor();
  const before=await page.locator('#pageCount').textContent();
  await page.getByRole('button',{name:'設定',exact:true}).click();
  dialog=page.getByRole('dialog',{name:'設定',exact:true});
  await dialog.locator('[data-tab=appearance]').click();
  await page.keyboard.press('ArrowDown'); await page.keyboard.press('f');
  assert.equal(await page.locator('#pageCount').textContent(),before);
  assert.equal(await page.locator('.present-screen').count(),0);
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('#hintKeys').isVisible(),false);
  assert.deepEqual(errors,[]);
  await app.close(); app=await launch(); page=await app.firstWindow();
  await page.getByRole('button',{name:'設定',exact:true}).click();
  assert.equal(await page.locator('html').getAttribute('data-theme'),'dark');
  assert.equal(await page.locator('html').getAttribute('data-key-hints'),'false');
});
