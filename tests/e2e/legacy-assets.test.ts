import assert from 'node:assert/strict';
import { mkdtemp, readFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createRequire } from 'node:module';
import test from 'node:test';
import { _electron } from 'playwright-core';
import { Workspace } from '../../packages/core/src/legacy-workspace.js';
import { new_figure } from '../../packages/core/src/legacy-figures.js';
const require=createRequire(import.meta.url);
test('original asset panel uploads, previews, deletes and restores image bytes in Electron', {timeout:60000}, async t=>{
  const temp=await mkdtemp(join(tmpdir(),'studio-assets-e2e-'));

  const ws=Workspace.open(join(temp,'workspace'));ws.new_deck('talk','test');await new_figure(ws,'chart',ws.shelf_dir('test'));
  const env:Record<string,string>=Object.fromEntries(Object.entries(process.env).filter((entry): entry is [string,string]=>entry[1]!==undefined));env.SLIDE_STUDIO_ELECTRON_HOME=join(temp,'profile');delete env.ELECTRON_RUN_AS_NODE;
 const installed=process.env.SLIDE_STUDIO_TEST_APP;
  const app=await _electron.launch({executablePath:installed?.endsWith('.app')?join(installed,'Contents/MacOS/Slide Studio'):installed||require('electron'),args:[...(installed?[]:[join(process.cwd(),'dist/apps/desktop/main.js')]),'--root',ws.root],env});
  t.after(async()=>{await app.close();await rm(temp,{recursive:true,force:true});});
  const page=await app.firstWindow();const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message));
  await page.waitForFunction(()=>!!sessionStorage.getItem('slide-studio:admin-token'));
  await page.goto(new URL('/deck/talk',page.url()).href);
  await page.getByRole('tab',{name:'素材',exact:true}).click();
  await page.locator('.as-kinds [data-kind="images"]').click();
  const chooser=page.waitForEvent('filechooser');
  await page.locator('.as-add').click();
  const png=Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aWZkAAAAASUVORK5CYII=','base64');
  await (await chooser).setFiles({name:'plot.png',mimeType:'image/png',buffer:png});
  const card=page.locator('.as-card').filter({hasText:'plot.png'});await card.waitFor();
  await page.waitForFunction(()=>{const img=document.querySelector('.as-card img') as HTMLImageElement;return img?.complete&&img.naturalWidth===1;});
  await card.click();const dialog=page.getByRole('dialog',{name:'素材のプレビュー'});await dialog.waitFor();
  assert.equal(await dialog.locator('img').getAttribute('alt'),'plot.png');
  await dialog.getByRole('button',{name:'閉じる',exact:true}).click();
  await page.locator('.as-bar [data-act="select"]').click();await card.click();
  await page.getByRole('button',{name:'選んだ素材を削除',exact:true}).click();
  await page.getByRole('dialog',{name:'素材を削除',exact:true}).getByRole('button',{name:'削除',exact:true}).click();
  await card.waitFor({state:'detached'});await page.keyboard.press('Meta+z');await card.waitFor();
  assert.deepEqual(await readFile(join(ws.asset_root('talk'),'images/plot.png')),png);
  await page.locator('.as-kinds [data-kind="html"]').click();
  const figure=page.locator('.as-card').filter({hasText:'chart'});await figure.click();
  const preview=page.getByRole('dialog',{name:'素材のプレビュー'});
  const frame=preview.frameLocator('iframe');await frame.locator('#stage[data-step="0"] svg').waitFor();
  await preview.getByRole('button',{name:'次のステップ',exact:true}).click();
  await frame.locator('#stage[data-step="1"] svg').waitFor();
  await preview.getByRole('button',{name:'前のステップ',exact:true}).click();
  await frame.locator('#stage[data-step="0"] svg').waitFor();
  await preview.getByRole('button',{name:'閉じる',exact:true}).click();
  assert.deepEqual(errors,[]);
});
